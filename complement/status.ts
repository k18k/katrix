// Keep a running ledger of Complement results and render it into README.md.
// Usage: node complement/status.ts [--reset] [--note "text"] results.json...
//   Each input is `go test -json` output from a full or targeted run; later files win.
//   --reset starts the ledger from scratch (use it with a full-suite run).
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const LEDGER = new URL("./results.json", import.meta.url);
const README = new URL("../README.md", import.meta.url);
const START = "<!-- complement-status:start -->";
const END = "<!-- complement-status:end -->";

interface Ledger {
  tests: Record<string, { status: string; pkg: string }>;
  history: { note: string; top: number; topTotal: number; sub: number; subTotal: number }[];
}

const args = process.argv.slice(2);
let reset = false;
let note = "";
const inputs: string[] = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--reset") reset = true;
  else if (args[i] === "--note") note = args[++i] ?? "";
  else inputs.push(args[i]);
}

const ledger: Ledger = !reset && existsSync(LEDGER) ? JSON.parse(readFileSync(LEDGER, "utf8")) : { tests: {}, history: [] };
if (reset) ledger.tests = {};

for (const file of inputs) {
  for (const line of readFileSync(file, "utf8").split("\n")) {
    if (!line.startsWith("{")) continue;
    let ev: { Action?: string; Test?: string; Package?: string };
    try {
      ev = JSON.parse(line);
    } catch {
      continue;
    }
    if (!ev.Test || !["pass", "fail", "skip"].includes(ev.Action ?? "")) continue;
    // https://github.com/k18k/matrix-nodejs-homeserver/issues/8: test names are used as keys; names like `__proto__` would write to the prototype.
    if (["__proto__", "constructor", "prototype"].includes(ev.Test)) continue;
    ledger.tests[ev.Test] = { status: ev.Action!, pkg: (ev.Package ?? "").replace(/^.*\/tests\/?/, "") || "federation" };
  }
}

const entries = Object.entries(ledger.tests);
const top = entries.filter(([n]) => !n.includes("/"));
const passing = (list: typeof entries) => list.filter(([, r]) => r.status === "pass").length;
const counted = (list: typeof entries) => list.filter(([, r]) => r.status !== "skip").length;
if (inputs.length) {
  ledger.history.push({
    note,
    top: passing(top),
    topTotal: counted(top),
    sub: passing(entries),
    subTotal: counted(entries),
  });
}
writeFileSync(LEDGER, JSON.stringify(ledger, null, 1) + "\n");

const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(1)}%` : "–");
const bar = (a: number, b: number, width = 20) => {
  const n = b ? Math.floor((width * a) / b) : 0;
  return "█".repeat(n) + "░".repeat(width - n);
};

const pkgs = new Map<string, typeof entries>();
for (const e of top) pkgs.set(e[1].pkg, [...(pkgs.get(e[1].pkg) ?? []), e]);

const failing = top
  .filter(([, r]) => r.status === "fail")
  .map(([n, r]) => `- \`${r.pkg}\` ${n}`)
  .sort();
const last = ledger.history.slice(-15).reverse();
const block = [
  START,
  "<!-- Generated by complement/status.ts; do not edit by hand. -->",
  "",
  `**${passing(top)} / ${counted(top)}** top-level tests passing (${pct(passing(top), counted(top))}) · ` +
    `**${passing(entries)} / ${counted(entries)}** including subtests (${pct(passing(entries), counted(entries))})`,
  "",
  "`" + bar(passing(entries), counted(entries)) + "`",
  "",
  "| Area | Passing | |",
  "|---|---|---|",
  ...[...pkgs]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([pkg, list]) => `| ${pkg} | ${passing(list)} / ${counted(list)} | \`${bar(passing(list), counted(list), 10)}\` |`),
  "",
  "<details><summary>Progress history</summary>",
  "",
  "| Run | Top-level | Subtests | Note |",
  "|---|---|---|---|",
  ...last.map((h) => `| ${ledger.history.indexOf(h) + 1} | ${h.top} / ${h.topTotal} | ${h.sub} / ${h.subTotal} | ${h.note} |`),
  "",
  "</details>",
  "",
  `<details><summary>Still failing (${failing.length})</summary>`,
  "",
  ...failing,
  "",
  "</details>",
  END,
].join("\n");

const readme = readFileSync(README, "utf8");
const at = readme.indexOf(START);
const updated =
  at >= 0
    ? readme.slice(0, at) + block + readme.slice(readme.indexOf(END) + END.length)
    : readme.replace(/(### Complement\n)/, `$1\n${block}\n`);
writeFileSync(README, updated);
console.log(`${passing(top)}/${counted(top)} top-level, ${passing(entries)}/${counted(entries)} subtests`);
